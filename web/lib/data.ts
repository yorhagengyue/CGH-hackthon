import "server-only";
import { db, one } from "./db";
import { DIMS, DIM_LABEL, LEVEL_LABEL, VALUE_SET, flag, type Dim } from "./eq5d";

export type Survey = { id: number; appointment_id: number | null; mo: number; sc: number; ua: number; pd: number; ad: number; eq_vas: number; pain: number; index_value: number; submitted_at: string; filled_by_name: string };
export type Appt = { id: number; referral_id: number; scheduled_at: string; kind: string; status: string; physio_name: string | null; survey_id: number | null };
export type Referral = { id: number; diagnosis: string; region: string; notes: string | null; status: string; created_at: string; doctor_name: string; physio_id: number | null; physio_name: string | null };

export async function patientBundle(patientId: number) {
  const q = await db();
  const patient = await one<{ id: number; login_id: string; name: string; phone: string | null; gender: string | null; birthday: string | null; address: string | null }>(
    "SELECT id, login_id, name, phone, gender, birthday::text AS birthday, address FROM users WHERE id = $1 AND role='patient'", [patientId]);
  if (!patient) return null;
  const referrals = await q<Referral>(`SELECT r.id, r.diagnosis, r.region, r.notes, r.status, r.created_at::text, d.name AS doctor_name, r.physio_id, p.name AS physio_name
    FROM referrals r JOIN users d ON d.id = r.doctor_id LEFT JOIN users p ON p.id = r.physio_id WHERE r.patient_id = $1 ORDER BY r.created_at DESC`, [patientId]);
  const appointments = await q<Appt>(`SELECT a.id, a.referral_id, a.scheduled_at::text, a.kind, a.status, p.name AS physio_name, s.id AS survey_id
    FROM appointments a LEFT JOIN users p ON p.id = a.physio_id LEFT JOIN surveys s ON s.appointment_id = a.id WHERE a.patient_id = $1 ORDER BY a.scheduled_at`, [patientId]);
  const surveys = await q<Survey>(`SELECT s.*, s.submitted_at::text, u.name AS filled_by_name FROM surveys s JOIN users u ON u.id = s.filled_by WHERE s.patient_id = $1 ORDER BY s.submitted_at`, [patientId]);
  const caregivers = await q<{ id: number; name: string; relationship: string; phone: string | null }>(`SELECT u.id, u.name, c.relationship, u.phone FROM care_links c JOIN users u ON u.id = c.caregiver_id WHERE c.patient_id = $1`, [patientId]);
  return { patient, referrals, appointments, surveys, caregivers };
}

export const levels = (s: Survey): Record<Dim, number> => ({ mo: s.mo, sc: s.sc, ua: s.ua, pd: s.pd, ad: s.ad });
export const profileStr = (s: Survey) => DIMS.map((d) => s[d]).join("");

export function clinicalNote(p: { name: string; login_id: string; gender: string | null; birthday: string | null }, dx: string | undefined, cur: Survey, prev: Survey | null, first: Survey | null) {
  const d = (a: Survey, b: Survey) => `index ${(a.index_value - b.index_value) >= 0 ? "+" : ""}${(a.index_value - b.index_value).toFixed(3)}, EQ-VAS ${a.eq_vas - b.eq_vas >= 0 ? "+" : ""}${a.eq_vas - b.eq_vas}, pain ${a.pain - b.pain >= 0 ? "+" : ""}${a.pain - b.pain}`;
  const when = new Date(cur.submitted_at).toLocaleString("en-SG", { timeZone: "Asia/Singapore" });
  const lines = [
    `PATIENT-REPORTED OUTCOME MEASURES (EQ-5D-5L) – ${when}`,
    `Patient: ${p.name} (${p.login_id.slice(0, 1)}****${p.login_id.slice(-4)})  ${p.gender ?? ""}  Dx: ${dx ?? "-"}`,
    `Completed online by ${cur.filled_by_name}.`,
    ``,
    `EQ-5D-5L profile ${profileStr(cur)}   index ${cur.index_value.toFixed(3)} (${VALUE_SET} value set)`,
    ...DIMS.map((k) => `  ${DIM_LABEL[k].padEnd(22)} level ${cur[k]}  ${LEVEL_LABEL[cur[k]]}`),
    `EQ-VAS (0-100)        ${cur.eq_vas}`,
    `Pain NRS (0-10)       ${cur.pain}`,
  ];
  if (prev) lines.push(``, `Change since last PROM ${new Date(prev.submitted_at).toLocaleDateString("en-SG", { timeZone: "Asia/Singapore" })} (profile ${profileStr(prev)}): ${d(cur, prev)}`);
  if (first && first.id !== prev?.id) lines.push(`Change since initial ${new Date(first.submitted_at).toLocaleDateString("en-SG", { timeZone: "Asia/Singapore" })} (profile ${profileStr(first)}): ${d(cur, first)}`);
  lines.push(``, `Generated by CGH Physio PROMs; reviewed by therapist before filing.`);
  return lines.join("\n");
}

export function flagsFor(cur: Survey | null, prev: Survey | null) {
  return { index: flag(prev?.index_value, cur?.index_value, "index"), vas: flag(prev?.eq_vas, cur?.eq_vas, "vas"), pain: flag(prev?.pain, cur?.pain, "pain", false) };
}

/** Today's (or a given day's) clinic list for a physio (or all physios when physioId is null). */
export async function clinicList(physioId: number | null, day = new Date()) {
  const q = await db();
  // Day boundaries in Singapore time, whatever the server's own time zone is (Vercel runs in UTC).
  const start = new Date(day.toLocaleDateString("en-CA", { timeZone: "Asia/Singapore" }) + "T00:00:00+08:00");
  const end = new Date(start.getTime() + 24 * 60 * 60 * 1000);
  const rows = await q<{ appt_id: number; scheduled_at: string; kind: string; patient_id: number; name: string; gender: string | null; birthday: string | null; diagnosis: string; region: string; physio_name: string | null; survey_id: number | null }>(
    `SELECT a.id AS appt_id, a.scheduled_at::text, a.kind, u.id AS patient_id, u.name, u.gender, u.birthday::text AS birthday, r.diagnosis, r.region, p.name AS physio_name, s.id AS survey_id
     FROM appointments a JOIN users u ON u.id = a.patient_id JOIN referrals r ON r.id = a.referral_id LEFT JOIN users p ON p.id = a.physio_id LEFT JOIN surveys s ON s.appointment_id = a.id
     WHERE a.scheduled_at >= $1 AND a.scheduled_at < $2 AND a.status <> 'cancelled' AND ($3::int IS NULL OR a.physio_id = $3) ORDER BY a.scheduled_at`, [start.toISOString(), end.toISOString(), physioId]);
  const out = [];
  for (const r of rows) {
    const hist = await q<Survey>(`SELECT s.*, s.submitted_at::text, u.name AS filled_by_name FROM surveys s JOIN users u ON u.id = s.filled_by WHERE s.patient_id = $1 ORDER BY s.submitted_at`, [r.patient_id]);
    const cur = r.survey_id ? hist.find((h) => h.id === r.survey_id) ?? null : null;
    const prev = hist.filter((h) => h.id !== r.survey_id).at(-1) ?? null;
    out.push({ ...r, cur, prev, nPrev: hist.filter((h) => h.id !== r.survey_id).length, flags: flagsFor(cur, prev) });
  }
  return out;
}
